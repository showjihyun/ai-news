export const RUBRIC_KEYS = RUBRIC.map((d) => d.key);

/** 가중 평균 (1~5 척도 유지). */
export function weightedScore(scores: Record<string, number>): number {
  let total = 0;
  let weight = 0;
  for (const d of RUBRIC) {
    const s = scores[d.key];
    if (typeof s !== 'number') continue;
    total += s * d.weight;
    weight += d.weight;
  }
  return weight === 0 ? 0 : total / weight;
}

export function rubricForPrompt(): string {
  return RUBRIC.map(
    (d) =>
      `### ${d.key} — ${d.name} (가중치 ${d.weight}%)\n` +
      `중요한 이유: ${d.why}\n` +
      `5점: ${d.best}\n` +
      `1점: ${d.worst}`,
  ).join('\n\n');
}

export function dimensionName(key: string): string {
  return RUBRIC.find((d) => d.key === key)?.name ?? key;
}
