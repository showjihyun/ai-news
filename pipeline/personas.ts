/**
 * 카테고리별 집필 페르소나.
 *
 * 왜 이렇게 하는가 — 두 가지 이유가 있다.
 *
 * 1) 차별화. AI 로 쓴 요약글은 서로 구별이 안 되고, 그러면 검색 순위에서 빠르게 밀린다.
 *    같은 뉴스라도 "투자 데스크가 보는 관점"과 "규제 데스크가 보는 관점"은 다른 글이 된다.
 *    각 페르소나에 고유한 분석 틀·어휘·항상 덧붙이는 것을 정의해서, 원문 요약이 아니라
 *    해석이 담긴 글이 나오게 만든다.
 *
 * 2) 정직함. 가상의 사람 이름과 경력을 지어내 붙이는 것은 구글 스팸 정책의
 *    '허위 표시(misrepresentation)' 에 해당하고, 적발되면 사이트 전체가 색인에서 빠진다.
 *    애드센스 수익을 지키려면 오히려 피해야 할 짓이다. 그래서 사람 이름 대신
 *    '데스크(편집 부서)' 라는 실체 있는 단위를 쓰고, 푸터에 AI 작성 사실을 밝힌다.
 *    전문성 있는 목소리는 그대로 얻으면서 리스크는 지지 않는다.
 *
 * angle 은 광고 단가가 높은 주제(투자·법률·커리어·요금)와 자연스럽게 이어지는
 * 서술 각도다. 억지로 끼워 넣으라는 뜻이 아니라, 그 관점이 실제로 유효할 때 살리라는 뜻.
 */
export interface Persona {
  /** 바이라인에 표시되는 이름 */
  desk: string;
  /** 이 데스크가 무엇을 보는 곳인지 (사이트 소개 페이지에도 노출) */
  beat: string;
  /** 시스템 프롬프트에 주입되는 목소리 지시 */
  voice: string;
  /** 이 데스크의 글에는 반드시 들어가야 하는 것 — 차별화의 실체 */
  alwaysInclude: string;
  /** 광고 단가가 높은 서술 각도 (해당될 때만 활용) */
  angle: string;
}

