/**
 * 반드시 들어가야 하는 섹션 제목.
 *
 * 프롬프트로 시켜도 모델이 빼먹는 일이 실제로 있었다(첫 3건 모두 누락).
 * '비전문가도 이해할 수 있게'가 이 사이트의 존재 이유이므로 코드로 확인하고 재시도한다.
 */
export const REQUIRED_SECTIONS = ['쉽게 풀어보면', '나에게 미치는 영향'] as const;

export function missingSections(body: string): string[] {
  const headings = [...body.matchAll(/^##\s+(.+?)\s*$/gm)].map((m) => m[1].trim());
  return REQUIRED_SECTIONS.filter((req) => !headings.some((h) => h.includes(req)));
}

